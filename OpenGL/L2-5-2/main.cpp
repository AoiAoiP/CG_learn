        PhongCubeShader.setVec3("viewPos", camera.GetPosition());
        
        PhongCubeShader.setFloat("light.constant", 1.0f);
        PhongCubeShader.setFloat("light.linear", 0.09f);
        PhongCubeShader.setFloat("light.quadratic", 0.032f);
        PhongCubeShader.setFloat("material.shininess", 32.0f);

        view = camera.GetViewMatrix(); 
