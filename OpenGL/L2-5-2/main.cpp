        PhongCubeShader.setMat4("projection", projection);
        model = glm::mat4(1.0f);
        PhongCubeShader.setMat4("model", model);

        // 绑定漫反射/镜反射贴图
        glActiveTexture(GL_TEXTURE0);
        glBindTexture(GL_TEXTURE_2D,diffuseMap);
